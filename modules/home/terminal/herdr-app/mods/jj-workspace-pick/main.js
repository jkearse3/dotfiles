// Opens `herdr-jj-workspace prompt-add --host app --pick` in a popup
// terminal, so a key binding (`ctrl-b shift-g`) can create a jj workspace in
// a repository picked with fzf: `mod.open` takes only a mod name. The picker
// lists the jj repositories of the spaces open on this machine, one line per
// repository however many of its workspaces are open; Enter asks for a name,
// runs `jjx workspace add` from `trunk()`, and opens and focuses the new
// space; Esc closes the popup without creating anything. `jj-workspace-new`
// (`ctrl-b ctrl-g`) skips the picker and uses the focused terminal's
// repository.
//
// The order matters. The launcher waits for `hc run` while still open,
// because closing it cancels its pending tasks and would leave the started
// terminal with no popup. Then, in one synchronous turn, it closes itself
// before opening the popup: opening focuses the popup's terminal, whereas a
// dialog closed afterwards would hand the keyboard to the popup's frame
// instead (herdr-app `src/window.rs` `remove_overlay`, `restore_focus`).
//
// The app documents imports only from a mod's own folder (herdr-app
// `defaults/AGENTS.md`), so `cliPath` and `startTerminal` are copied into
// each launcher that uses them rather than shared.

import { View, div } from "gpui-kit";
import {
  appHome,
  closeOverlay,
  hc,
  home,
  notify,
  openOverlay,
  props,
  readTextFile,
} from "herdr";

const TITLE = "New jj workspace";

// Generated by the dotfiles' Home Manager module: CLI name -> absolute store
// path. A bare name would resolve on the core's PATH, which depends on
// whoever started the core.
async function cliPath(name) {
  const text = await readTextFile(`${appHome()}/dotfiles-paths.json`);
  const path = text === null ? undefined : JSON.parse(text)[name];
  if (!path) {
    throw new Error(
      `dotfiles-paths.json names no ${name}; run a Home Manager switch.`,
    );
  }
  return path;
}

// Starts ARGV in FOLDER in a new core terminal and returns its address. No
// herdr labels, so it never becomes a pane; no parent, so it never types
// notes into the terminal that happened to be focused; `--rm`, so no
// finished record stays behind.
async function startTerminal(folder, argv) {
  const r = await hc([
    "run",
    "--bg",
    "--rm",
    "--no-parent",
    "--no-notify",
    "--json",
    "--cwd",
    folder,
    "--",
    ...argv,
  ]);
  if (r.code !== 0) {
    throw new Error(r.stderr.trim() || `hc run exited with ${r.code}`);
  }
  const address = JSON.parse(r.stdout).address;
  if (!address) throw new Error("hc run printed no terminal address.");
  return address;
}

export default class JjWorkspacePick extends View {
  init(_props, cx) {
    // `herdr-app check` renders the mod with no props, outside an overlay.
    // Start nothing then: `hc` would start a core when none runs.
    const overlay = props()?.overlay;
    if (!overlay) return;

    cx.spawn(async (_cx) => {
      let terminal;
      try {
        const cli = await cliPath("herdr-jj-workspace");
        // The picker reads its repositories from the app's spaces, not from
        // its working directory.
        terminal = await startTerminal(home(), [
          cli,
          "prompt-add",
          "--host",
          "app",
          "--pick",
        ]);
      } catch (error) {
        closeOverlay(overlay);
        notify({
          title: TITLE,
          body: String(error?.message ?? error),
          level: "error",
        });
        return;
      }

      closeOverlay(overlay);
      openOverlay({
        kind: "dialog",
        // A click beside it does not close it; Esc goes to the picker.
        modal: true,
        width: 0.6,
        height: 0.5,
        layout: {
          type: "column",
          children: [
            {
              type: "block",
              size: { px: 30 },
              content: { mod: "popup", props: { terminal, title: TITLE } },
            },
            { type: "block", content: { terminal } },
          ],
        },
      });
    });
  }

  render(_cx) {
    return div();
  }
}
