// Where mods find programs and folders: a program's absolute store path
// (`cliPath`), the focused terminal's folder (`focusedFolder`), and where a
// space is now (`place`).
//
// The deploy tree copies this file into each mod folder that deploy.nix
// `sharedModFiles` lists, at build time, so edit it here rather than in a
// deployed copy. It is copied because the app refuses imports that leave a
// mod's own folder; `./paths.js` beside the importing file is allowed.

import { appHome, focused, panes, readTextFile, spaces } from "herdr";

// The absolute store path that dotfiles-paths.json, generated by the
// dotfiles' Home Manager module, maps program name NAME to; it reads the file
// on every call. A bare name would resolve on the PATH of the core or the app,
// whichever runs the program, and that PATH depends on how it was started.
// Throws when the file or its entry is missing.
export async function cliPath(name) {
  const text = await readTextFile(`${appHome()}/dotfiles-paths.json`);
  const path = text === null ? undefined : JSON.parse(text)[name];
  if (!path) {
    throw new Error(
      `dotfiles-paths.json names no ${name}; run a Home Manager switch.`,
    );
  }
  return path;
}

// The focused terminal's live folder when that terminal is on this machine,
// else null: a mod pane, no focus, or a terminal of another machine. This
// follows the app's own `files` mod.
export function focusedFolder() {
  const f = focused();
  if (!f) return null;
  const machine = f.pane
    ? spaces().find((s) => s.id === f.space)?.machine
    : f.terminal?.includes("/")
      ? f.terminal.split("/")[0]
      : null;
  if (machine !== null) return null; // undefined (space not found) counts as unknown
  const pane = f.pane ? panes().find((p) => p.pane === f.pane) : null;
  return pane?.cwd || f.cwd || null;
}

// Where SPACE is now: its first terminal's live folder, else the folder it
// was made in, which may be empty. `ps` is `panes()`; a caller placing many
// spaces reads it once and passes it in, since each read copies every pane.
export function place(space, ps = panes()) {
  const tabs = new Set((space.tabs ?? []).map((t) => t.id));
  return ps.find((p) => tabs.has(p.tab) && p.cwd)?.cwd || space.folder;
}
