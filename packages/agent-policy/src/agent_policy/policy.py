"""Load and validate the agent command policy file.

The policy file is JSON generated by Nix. Its shape::

    {
      "tools": {
        "<tool>": {
          "executable": "/absolute/path/to/real/binary",
          "prefix-arguments": ["--config", "name=value"],
          "global-options-position": "anywhere" | "before-subcommand",
          "global-options": [{"names": ["-R", "--repository"], "arity": "value"}],
          "rules": [<rule>, ...]
        }
      }
    }

Every rule has an ``id`` of the form ``<tool>.<rule>``, unique across the
file, a ``kind``, a ``scope`` (``"any"`` or a subcommand path such as
``["git", "push"]``), and a ``message`` explaining why the rule exists and
what the safe alternative is. Kinds and their extra keys:

- ``refuse-option``: ``refused-options``, option names refused anywhere
  before ``--`` in an invocation the scope covers.
- ``refuse-subcommand``: no extra keys; refuses every invocation the scope
  covers. The scope must be a subcommand path.
- ``allowlist``: ``allowed-options`` (option declarations, each optionally
  with a ``value-constraint``), ``allowed-global-options`` (names of tool
  global options the rule accepts), ``target-options`` (allowed options whose
  every occurrence names one thing the command acts on; when present, an
  invocation must name at least one target), ``informational-options``
  (allowed options that make the tool only print information, which waive the
  target requirement and named checks), and ``checks`` (names of registered
  named checks). Every other option in scope is refused.

Option arity is ``flag``, ``value`` (``-X v``, ``-Xv``, ``-X=v``,
``--long v``, ``--long=v``), or ``optional-value`` (long names only, value
only as ``--long=v``).

Loading validates the whole file and reports every problem at once, so an
invalid policy fails the Nix build that runs ``agent-policy validate``.
"""

from __future__ import annotations

import json
import re
from collections.abc import Collection, Mapping, Sequence
from dataclasses import dataclass
from enum import StrEnum
from pathlib import Path
from typing import TypeVar, cast, final

from .checks import NAMED_CHECKS


class PolicyError(Exception):
    """A policy file that cannot be read or does not satisfy the policy schema.

    ``problems`` lists every violation found, each locating its JSON path.
    """

    def __init__(self, problems: Sequence[str]) -> None:
        super().__init__("; ".join(problems))
        self.problems: tuple[str, ...] = tuple(problems)


@dataclass(frozen=True)
class Policy:
    """Every governed tool, keyed by the tool name its shim passes to ``run``."""

    tools: Mapping[str, Tool]


@dataclass(frozen=True)
class Tool:
    """A governed command-line tool and the rules its invocations must pass."""

    name: str
    executable: str
    """Absolute path of the real binary the engine executes when allowed."""
    prefix_arguments: tuple[str, ...]
    """Arguments always inserted between the executable and the agent's argv."""
    global_options_position: GlobalOptionsPosition
    global_options: tuple[OptionDeclaration, ...]
    rules: tuple[Rule, ...]

    @property
    def real_command(self) -> tuple[str, ...]:
        """Return the executable followed by the forced prefix arguments."""
        return (self.executable, *self.prefix_arguments)


class GlobalOptionsPosition(StrEnum):
    """Where a tool accepts its global options before ``--``."""

    ANYWHERE = "anywhere"
    """Between and after subcommand words too, as clap-based tools like jj allow."""
    BEFORE_SUBCOMMAND = "before-subcommand"
    """Only before the first subcommand word, as git requires."""


class OptionArity(StrEnum):
    """Whether and how an option takes a value."""

    FLAG = "flag"
    VALUE = "value"
    OPTIONAL_VALUE = "optional-value"
    """A value only in ``--long=value`` form; the bare option is a flag."""


class ValueConstraint(StrEnum):
    """A restriction on an allowed option's value."""

    LITERAL_NAME = "literal-name"
    """The value names exactly one thing: no pattern syntax or kind prefix
    other than ``exact:``, optionally as one double-quoted jj string."""
    LITERAL_NAME_BEFORE_EQUALS = "literal-name-before-equals"
    """The value is ``<name>=<anything>`` and ``<name>`` is a literal name."""


@final
@dataclass(frozen=True)
class OptionDeclaration:
    """One option, all its spellings, and how it takes a value."""

    names: tuple[str, ...]
    arity: OptionArity
    value_constraint: ValueConstraint | None = None
    """Constraint on the value; ``None`` accepts any value."""


@dataclass(frozen=True)
class RuleScope:
    """The invocations a rule applies to.

    ``subcommand_path`` ``None`` applies to every invocation of the tool;
    otherwise an invocation is covered when its subcommand words start with
    the path.
    """

    subcommand_path: tuple[str, ...] | None


@dataclass(frozen=True)
class RefuseOptionRule:
    """Refuse a covered invocation that uses any of ``refused_options``."""

    id: str
    scope: RuleScope
    message: str
    refused_options: tuple[OptionDeclaration, ...]


@dataclass(frozen=True)
class RefuseSubcommandRule:
    """Refuse every invocation the scope covers."""

    id: str
    scope: RuleScope
    message: str


@dataclass(frozen=True)
class AllowlistRule:
    """Refuse a covered invocation that uses any option outside the allowlist.

    Options another in-scope rule of the same tool refuses are left to that
    rule. Named ``checks`` run only when the allowlist itself has no
    objection, and their refusals belong to this rule's ID.
    """

    id: str
    scope: RuleScope
    message: str
    allowed_options: tuple[OptionDeclaration, ...]
    allowed_global_options: frozenset[OptionDeclaration]
    target_options: frozenset[OptionDeclaration]
    """Options whose every occurrence names one target; empty means no
    target is required."""
    informational_options: frozenset[OptionDeclaration]
    checks: tuple[str, ...]


Rule = RefuseOptionRule | RefuseSubcommandRule | AllowlistRule


def load_policy(path: Path) -> Policy:
    """Read and validate the policy file at PATH.

    Raises ``PolicyError`` listing every problem when the file is unreadable,
    is not JSON, or violates the schema.
    """
    try:
        document = cast(object, json.loads(path.read_text(encoding="utf-8")))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as error:
        raise PolicyError([f"cannot read policy: {error}"]) from error
    return parse_policy(document)


def parse_policy(document: object) -> Policy:
    """Validate a decoded policy DOCUMENT and build the typed policy.

    Raises ``PolicyError`` listing every problem found.
    """
    reader = _PolicyReader()
    policy = reader.policy(document)
    if len(reader.problems) > 0:
        raise PolicyError(reader.problems)
    if policy is None:
        raise PolicyError(["policy is empty"])
    return policy


_Enum = TypeVar("_Enum", bound=StrEnum)

_SHORT_OPTION = re.compile(r"-[A-Za-z0-9]")
_LONG_OPTION = re.compile(r"--[A-Za-z0-9][A-Za-z0-9-]*")

# Each rule kind's (required, optional) keys beyond the common ones.
_RULE_KEYS: Mapping[str, tuple[frozenset[str], frozenset[str]]] = {
    "refuse-option": (frozenset({"refused-options"}), frozenset()),
    "refuse-subcommand": (frozenset(), frozenset()),
    "allowlist": (
        frozenset(),
        frozenset(
            {
                "allowed-options",
                "allowed-global-options",
                "target-options",
                "informational-options",
                "checks",
            }
        ),
    ),
}
_COMMON_RULE_KEYS = frozenset({"id", "kind", "scope", "message"})


class _PolicyReader:
    """Build typed policy objects while collecting every schema problem."""

    def __init__(self) -> None:
        self.problems: list[str] = []
        self._rule_ids: set[str] = set()

    def policy(self, document: object) -> Policy | None:
        root = self._object(document, "policy", required={"tools"}, optional=set())
        if root is None:
            return None

        tools_document = self._object(root.get("tools"), "tools", required=None)
        if tools_document is None:
            return None

        tools: dict[str, Tool] = {}
        for name, tool_document in tools_document.items():
            tool = self._tool(name, tool_document)
            if tool is not None:
                tools[name] = tool
        return Policy(tools)

    def _tool(self, name: str, document: object) -> Tool | None:
        where = f"tools.{name}"
        tool = self._object(
            document,
            where,
            required={
                "executable",
                "prefix-arguments",
                "global-options-position",
                "global-options",
                "rules",
            },
            optional=set(),
        )
        if tool is None:
            return None
        if re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_-]*", name) is None:
            self.problems.append(f"{where}: tool name must be a plain word")

        executable = self._string(tool["executable"], f"{where}.executable")
        if executable is not None and not executable.startswith("/"):
            self.problems.append(f"{where}.executable: must be an absolute path")
        prefix_arguments = self._strings(
            tool["prefix-arguments"], f"{where}.prefix-arguments", allow_empty=True
        )
        position = self._enum(
            GlobalOptionsPosition,
            tool["global-options-position"],
            f"{where}.global-options-position",
        )
        global_options = self._declarations(
            tool["global-options"], f"{where}.global-options", allow_constraints=False
        )

        rules_document = self._list(tool["rules"], f"{where}.rules")
        rules: list[Rule] = []
        if rules_document is not None and global_options is not None:
            for index, rule_document in enumerate(rules_document):
                rule = self._rule(name, global_options, rule_document, f"{where}.rules[{index}]")
                if rule is not None:
                    rules.append(rule)

        if executable is None or prefix_arguments is None or position is None or global_options is None:
            return None
        return Tool(
            name=name,
            executable=executable,
            prefix_arguments=prefix_arguments,
            global_options_position=position,
            global_options=global_options,
            rules=tuple(rules),
        )

    def _rule(
        self,
        tool_name: str,
        global_options: tuple[OptionDeclaration, ...],
        document: object,
        where: str,
    ) -> Rule | None:
        kind = cast(dict[str, object], document).get("kind") if isinstance(document, dict) else None
        if not isinstance(kind, str) or kind not in _RULE_KEYS:
            self.problems.append(
                f"{where}.kind: unknown kind {kind!r}; expected one of {', '.join(sorted(_RULE_KEYS))}"
            )
            return None
        required_keys, optional_keys = _RULE_KEYS[kind]
        rule = self._object(
            document,
            where,
            required=_COMMON_RULE_KEYS | required_keys,
            optional=optional_keys,
        )
        if rule is None:
            return None

        rule_id = self._rule_id(tool_name, rule["id"], f"{where}.id")
        if rule_id is not None:
            where = f"{where} ({rule_id})"
        scope = self._scope(rule["scope"], f"{where}.scope")
        message = self._string(rule["message"], f"{where}.message")
        if rule_id is None or scope is None or message is None:
            return None

        match kind:
            case "refuse-option":
                return self._refuse_option_rule(rule_id, scope, message, global_options, rule, where)
            case "refuse-subcommand":
                if scope.subcommand_path is None:
                    self.problems.append(f"{where}.scope: refuse-subcommand needs a subcommand path")
                    return None
                return RefuseSubcommandRule(id=rule_id, scope=scope, message=message)
            case _:
                return self._allowlist_rule(rule_id, scope, message, global_options, rule, where)

    def _refuse_option_rule(
        self,
        rule_id: str,
        scope: RuleScope,
        message: str,
        global_options: tuple[OptionDeclaration, ...],
        rule: Mapping[str, object],
        where: str,
    ) -> RefuseOptionRule | None:
        names = self._option_names(rule["refused-options"], f"{where}.refused-options")
        if names is None:
            return None

        # A refused global option keeps its declared arity so value forms such
        # as `--at-op=x` are recognized; any other name is matched as a flag.
        refused: list[OptionDeclaration] = []
        for name in names:
            declaration = _declaration_named(global_options, name)
            refused.append(declaration if declaration is not None else OptionDeclaration((name,), OptionArity.FLAG))
        return RefuseOptionRule(
            id=rule_id,
            scope=scope,
            message=message,
            refused_options=tuple(dict.fromkeys(refused)),
        )

    def _allowlist_rule(
        self,
        rule_id: str,
        scope: RuleScope,
        message: str,
        global_options: tuple[OptionDeclaration, ...],
        rule: Mapping[str, object],
        where: str,
    ) -> AllowlistRule | None:
        allowed_options = self._declarations(
            rule.get("allowed-options", []), f"{where}.allowed-options", allow_constraints=True
        )
        if allowed_options is None:
            return None
        for declaration in allowed_options:
            for name in declaration.names:
                if _declaration_named(global_options, name) is not None:
                    self.problems.append(
                        f"{where}.allowed-options: {name} is a global option; list it in allowed-global-options"
                    )

        allowed_global_options = self._references(
            rule.get("allowed-global-options", []),
            global_options,
            f"{where}.allowed-global-options",
            "a declared global option",
        )
        target_options = self._references(
            rule.get("target-options", []),
            allowed_options,
            f"{where}.target-options",
            "an allowed option",
        )
        informational_options = self._references(
            rule.get("informational-options", []),
            allowed_options + tuple(allowed_global_options if allowed_global_options is not None else ()),
            f"{where}.informational-options",
            "an allowed option or allowed global option",
        )
        checks = self._strings(rule.get("checks", []), f"{where}.checks", allow_empty=True)
        if checks is not None:
            for check in checks:
                if check not in NAMED_CHECKS:
                    known = ", ".join(sorted(NAMED_CHECKS)) if len(NAMED_CHECKS) > 0 else "none"
                    self.problems.append(f"{where}.checks: unknown check {check!r}; known checks: {known}")

        if (
            allowed_global_options is None
            or target_options is None
            or informational_options is None
            or checks is None
        ):
            return None
        return AllowlistRule(
            id=rule_id,
            scope=scope,
            message=message,
            allowed_options=allowed_options,
            allowed_global_options=frozenset(allowed_global_options),
            target_options=frozenset(target_options),
            informational_options=frozenset(informational_options),
            checks=checks,
        )

    def _rule_id(self, tool_name: str, value: object, where: str) -> str | None:
        rule_id = self._string(value, where)
        if rule_id is None:
            return None
        if re.fullmatch(rf"{re.escape(tool_name)}\.[a-z0-9][a-z0-9-]*", rule_id) is None:
            self.problems.append(
                f"{where}: rule ID {rule_id!r} must be {tool_name}.<rule> with a lowercase kebab-case rule name"
            )
            return None
        if rule_id in self._rule_ids:
            self.problems.append(f"{where}: duplicate rule ID {rule_id!r}")
            return None
        self._rule_ids.add(rule_id)
        return rule_id

    def _scope(self, value: object, where: str) -> RuleScope | None:
        if value == "any":
            return RuleScope(None)
        path = self._strings(value, where, allow_empty=False)
        if path is None:
            self.problems.append(f"{where}: expected \"any\" or a non-empty list of subcommand words")
            return None
        if any(word == "" or word.startswith("-") for word in path):
            self.problems.append(f"{where}: subcommand words must be non-empty and not options")
            return None
        return RuleScope(path)

    def _declarations(
        self, value: object, where: str, *, allow_constraints: bool
    ) -> tuple[OptionDeclaration, ...] | None:
        documents = self._list(value, where)
        if documents is None:
            return None

        declarations: list[OptionDeclaration] = []
        seen_names: set[str] = set()
        for index, document in enumerate(documents):
            declaration = self._declaration(document, f"{where}[{index}]", allow_constraints)
            if declaration is None:
                continue
            for name in declaration.names:
                if name in seen_names:
                    self.problems.append(f"{where}[{index}]: option {name} is declared twice")
                seen_names.add(name)
            declarations.append(declaration)
        if len(declarations) != len(documents):
            return None
        return tuple(declarations)

    def _declaration(
        self, document: object, where: str, allow_constraints: bool
    ) -> OptionDeclaration | None:
        declaration = self._object(
            document,
            where,
            required={"names", "arity"},
            optional={"value-constraint"} if allow_constraints else set(),
        )
        if declaration is None:
            return None

        names = self._option_names(declaration["names"], f"{where}.names")
        arity = self._enum(OptionArity, declaration["arity"], f"{where}.arity")
        constraint_value = declaration.get("value-constraint")
        constraint = (
            None
            if constraint_value is None
            else self._enum(ValueConstraint, constraint_value, f"{where}.value-constraint")
        )
        if names is None or arity is None or (constraint_value is not None and constraint is None):
            return None

        if arity is OptionArity.OPTIONAL_VALUE and any(_SHORT_OPTION.fullmatch(name) is not None for name in names):
            self.problems.append(f"{where}: optional-value options must have only long names")
            return None
        if arity is OptionArity.FLAG and constraint is not None:
            self.problems.append(f"{where}: a flag cannot have a value-constraint")
            return None
        return OptionDeclaration(names=names, arity=arity, value_constraint=constraint)

    def _option_names(self, value: object, where: str) -> tuple[str, ...] | None:
        names = self._strings(value, where, allow_empty=False)
        if names is None:
            return None
        malformed = [
            name
            for name in names
            if _SHORT_OPTION.fullmatch(name) is None and _LONG_OPTION.fullmatch(name) is None
        ]
        if len(malformed) > 0:
            self.problems.append(
                f"{where}: malformed option names {malformed}; expected -X or --long-name"
            )
            return None
        return names

    def _references(
        self,
        value: object,
        declarations: Sequence[OptionDeclaration],
        where: str,
        expected: str,
    ) -> list[OptionDeclaration] | None:
        names = self._strings(value, where, allow_empty=True)
        if names is None:
            return None

        referenced: list[OptionDeclaration] = []
        for name in names:
            declaration = _declaration_named(declarations, name)
            if declaration is None:
                self.problems.append(f"{where}: {name} is not {expected}")
                return None
            referenced.append(declaration)
        return referenced

    def _object(
        self,
        value: object,
        where: str,
        *,
        required: Collection[str] | None,
        optional: Collection[str] = (),
    ) -> dict[str, object] | None:
        """Return VALUE as a JSON object, checking keys unless REQUIRED is None."""
        if not isinstance(value, dict):
            self.problems.append(f"{where}: expected an object")
            return None
        document = cast(dict[str, object], value)
        if required is None:
            return document

        missing = sorted(set(required) - document.keys())
        unknown = sorted(document.keys() - set(required) - set(optional))
        if len(missing) > 0:
            self.problems.append(f"{where}: missing keys {missing}")
        if len(unknown) > 0:
            self.problems.append(f"{where}: unknown keys {unknown}")
        return None if len(missing) + len(unknown) > 0 else document

    def _list(self, value: object, where: str) -> list[object] | None:
        if not isinstance(value, list):
            self.problems.append(f"{where}: expected a list")
            return None
        return cast(list[object], value)

    def _string(self, value: object, where: str) -> str | None:
        if not isinstance(value, str) or value == "":
            self.problems.append(f"{where}: expected a non-empty string")
            return None
        return value

    def _strings(self, value: object, where: str, *, allow_empty: bool) -> tuple[str, ...] | None:
        items = self._list(value, where)
        if items is None:
            return None
        if not allow_empty and len(items) == 0:
            self.problems.append(f"{where}: expected a non-empty list")
            return None
        if not all(isinstance(item, str) for item in items):
            self.problems.append(f"{where}: expected a list of strings")
            return None
        return tuple(cast(list[str], items))

    def _enum(self, enum_type: type[_Enum], value: object, where: str) -> _Enum | None:
        if isinstance(value, str):
            for member in enum_type:
                if member.value == value:
                    return member
        expected = ", ".join(member.value for member in enum_type)
        self.problems.append(f"{where}: unknown value {value!r}; expected one of {expected}")
        return None


def _declaration_named(declarations: Sequence[OptionDeclaration], name: str) -> OptionDeclaration | None:
    """Return the declaration that has NAME among its spellings."""
    for declaration in declarations:
        if name in declaration.names:
            return declaration
    return None
